import stat
from pathlib import Path

import dotenv

from scripts.gen_env import render_env, write_env_file


def test_write_env_file_roundtrip_and_permissions(tmp_path: Path) -> None:
    values = {"A": 'he said "hi"', "B": "x#y=z", "C": "two words", "D": "line1\nline2"}
    path = tmp_path / ".env"
    path.write_text("junk")
    path.chmod(0o644)
    write_env_file(path, values)
    assert stat.S_IMODE(path.stat().st_mode) == 0o600
    assert dotenv.dotenv_values(path) == values
    assert list(tmp_path.iterdir()) == [path]


def test_render_env_sorted_keys() -> None:
    out = render_env({"B": "2", "A": "1"})
    assert out.startswith("# GENERATED by make env from AWS Secrets Manager — do not edit\n")
    assert out.index("A=") < out.index("B=")
