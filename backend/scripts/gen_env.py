"""Generate the git-ignored .env from AWS Secrets Manager (run via `make env`)."""

import argparse
import os
import sys
from collections.abc import Mapping
from pathlib import Path

HEADER = "# GENERATED by make env from AWS Secrets Manager — do not edit"


def _quote(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'


def render_env(values: Mapping[str, str]) -> str:
    lines = [HEADER] + [f"{key}={_quote(values[key])}" for key in sorted(values)]
    return "\n".join(lines) + "\n"


def write_env_file(path: Path, values: Mapping[str, str]) -> None:
    tmp = path.with_name(f".{path.name}.tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(render_env(values))
        os.replace(tmp, path)
    except BaseException:
        tmp.unlink(missing_ok=True)
        raise


def main(argv: list[str] | None = None) -> int:
    from app.core.secrets import SecretsError, load_secret

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--secret-id", required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--region", default="us-west-2")
    args = parser.parse_args(argv)
    try:
        values = load_secret(args.secret_id, region=args.region)
    except SecretsError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    write_env_file(args.out, values)
    print(f"wrote {len(values)} keys to {args.out}")
    return 0


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    raise SystemExit(main())
